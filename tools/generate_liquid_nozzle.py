"""Generate the static square Laval shell and its matching emissive lining profile."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'src/main/resources/assets/around_planet/models/block'
# Model pixels: converging chamber, narrow throat, expanding bell, slightly tucked lip.
Y = [9, 7, 5, 3, 0, -3, -6, -8, -10]
R = [4, 2.88, 2, 2.64, 4.32, 5.76, 6.64, 6.88, 6.56]
WALL = .8
lines = ['# Generated by tools/generate_liquid_nozzle.py', 'mtllib liquid_rocket_engine.mtl',
         'vt 0 0', 'vt 0 1', 'vt 1 1', 'vt 1 0']
vertices = 0

def quad(points, material):
    global vertices
    lines.append('usemtl ' + material)
    for x, y, z in points:
        lines.append(f'v {x/16:.7f} {y/16:.7f} {z/16:.7f}')
    lines.append('f ' + ' '.join(f'{vertices+i+1}/{i+1}' for i in range(4)))
    vertices += 4

def box(a, b, material):
    x,y,z = a; X,T,Z = b
    for face in [((x,y,z),(x,T,z),(X,T,z),(X,y,z)),
                 ((x,y,Z),(X,y,Z),(X,T,Z),(x,T,Z)),
                 ((x,y,z),(x,y,Z),(x,T,Z),(x,T,z)),
                 ((X,y,z),(X,T,z),(X,T,Z),(X,y,Z)),
                 ((x,T,z),(x,T,Z),(X,T,Z),(X,T,z)),
                 ((x,y,z),(X,y,z),(X,y,Z),(x,y,Z))]:
        quad(face, material)

def ring(y, r):
    return [(8-r,y,8-r),(8-r,y,8+r),(8+r,y,8+r),(8+r,y,8-r)]

box((0,13,0),(16,16,16),'body')
box((2,9,2),(14,13,14),'body')
for a,b in [((1.75,11,1.75),(14.25,12,2.5)),((1.75,11,13.5),(14.25,12,14.25)),
            ((1.75,11,2.5),(2.5,12,13.5)),((13.5,11,2.5),(14.25,12,13.5))]:
    box(a,b,'band')
for x,z in [(3,7),(11.5,7),(7,3),(7,11.5)]:
    box((x,6,z),(x+1.5,13,z+1.5),'pipe')
for i in range(len(Y)-1):
    top, bottom = ring(Y[i],R[i]), ring(Y[i+1],R[i+1])
    inner_top, inner_bottom = ring(Y[i],R[i]-WALL), ring(Y[i+1],R[i+1]-WALL)
    for s in range(4):
        n=(s+1)%4
        quad([top[s],bottom[s],bottom[n],top[n]],'nozzle')
        quad([inner_top[n],inner_bottom[n],inner_bottom[s],inner_top[s]],'inner')
# Close the wall thickness at the two ends, leaving the outlet fully open.
for i in [0,len(Y)-1]:
    outer, inner = ring(Y[i],R[i]), ring(Y[i],R[i]-WALL)
    for s in range(4):
        n=(s+1)%4
        face=[outer[s],outer[n],inner[n],inner[s]]
        quad(face if i==0 else face[::-1],'dark')
quad(ring(8.99,R[0]-WALL-.02)[::-1],'inner')
ASSETS.joinpath('liquid_rocket_engine.obj').write_text('\n'.join(lines)+'\n')
ASSETS.joinpath('liquid_rocket_engine.mtl').write_text(''.join(
    f'newmtl {mat}\nKd 1 1 1\nKa 0 0 0\nmap_Kd #{mat}\n\n'
    for mat in ['body','band','pipe','inner','dark','nozzle']))
model = {'loader':'neoforge:obj','model':'around_planet:models/block/liquid_rocket_engine.obj',
         'automatic_culling':False,'shade_quads':True,'flip_v':True,
         'textures':{'nozzle':'minecraft:block/polished_deepslate','body':'minecraft:block/iron_block','band':'minecraft:block/cyan_concrete',
                     'pipe':'minecraft:block/copper_block','inner':'minecraft:block/polished_blackstone',
                     'dark':'minecraft:block/deepslate_tiles','particle':'minecraft:block/iron_block'},
         'display':{'gui':{'rotation':[30,225,0],'translation':[0,3,0],'scale':[.48]*3},
                    'ground':{'translation':[0,5,0],'scale':[.3]*3},
                    'fixed':{'translation':[0,3,0],'scale':[.5]*3}}}
ASSETS.joinpath('liquid_rocket_engine.json').write_text(json.dumps(model,indent=2)+'\n')
java = ROOT / 'src/main/java/io/github/astelev/around_planet/propulsion/LiquidNozzleProfile.java'
java.write_text('''package io.github.astelev.around_planet.propulsion;
/** Generated by tools/generate_liquid_nozzle.py; model pixels shared with the active lining. */
public final class LiquidNozzleProfile {
    private static final double[] Y={%s},R={%s};
    public static int rings(){return Y.length;}
    public static float y(int ring){return (float)(Y[ring]/16-.5);}
    public static float inner(int ring){return (float)((R[ring]-.8)/16);}
    public static float outlet(){return y(Y.length-1)-.005f;}
    public static float plumeScale(){return inner(Y.length-1)/.24f;}
    private LiquidNozzleProfile(){}
}
''' % (','.join(map(str,Y)),','.join(map(str,R))))
